"""Gatus endpoint management.

Source of truth: /usr/local/netdash/data/gatus-endpoints.json (list of Gatus endpoint dicts).
Rendered to /usr/local/gatus/config/50-netdash.yaml; Gatus reads the whole config directory
(00-base.yaml = hand-written base, alerting, templates, external endpoints) and reloads on change.
Every save is test-run with the real Gatus binary on a scratch port before it goes live.
"""
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time

DATA_DIR = os.environ.get("NETDASH_DATA", "/usr/local/netdash/data")
STORE = os.path.join(DATA_DIR, "gatus-endpoints.json")
BACKUPS = os.path.join(DATA_DIR, "gatus-backups")
GATUS_DIR = CONF_DIR = OUT = BIN = ENV = None


def set_dir(path):
    """Gatus install dir: <dir>/gatus (binary), <dir>/gatus.env, <dir>/config/ (read as a whole by Gatus)"""
    global GATUS_DIR, CONF_DIR, OUT, BIN, ENV
    GATUS_DIR = path or "/usr/local/gatus"
    CONF_DIR = os.path.join(GATUS_DIR, "config")
    OUT = os.path.join(CONF_DIR, "50-netdash.yaml")
    BIN = os.path.join(GATUS_DIR, "gatus")
    ENV = os.path.join(GATUS_DIR, "gatus.env")


set_dir(os.environ.get("NETDASH_GATUS_DIR"))

ORDER = ["name", "group", "enabled", "url", "method", "interval", "headers", "body", "graphql", "client", "dns",
         "ssh", "conditions", "alerts", "ui"]
SAFE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def _scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v), ensure_ascii=False)


def _key(k):
    return k if SAFE_KEY.match(k) else json.dumps(k, ensure_ascii=False)


def to_yaml(obj, ind=0):
    pad = "  " * ind
    out = []
    if isinstance(obj, dict):
        keys = sorted(obj, key=lambda k: (ORDER.index(k) if k in ORDER else 99, k))
        for k in keys:
            v = obj[k]
            if isinstance(v, (dict, list)) and v:
                out.append("%s%s:" % (pad, _key(k)))
                out.append(to_yaml(v, ind + 1))
            elif isinstance(v, (dict, list)):
                out.append("%s%s: %s" % (pad, _key(k), "{}" if isinstance(v, dict) else "[]"))
            else:
                out.append("%s%s: %s" % (pad, _key(k), _scalar(v)))
    elif isinstance(obj, list):
        for v in obj:
            if isinstance(v, dict) and v:
                body = to_yaml(v, ind + 1).split("\n")
                out.append("%s- %s" % (pad, body[0].lstrip()))
                out.extend(body[1:])
            elif isinstance(v, list) and v:
                out.append("%s-" % pad)
                out.append(to_yaml(v, ind + 1))
            else:
                out.append("%s- %s" % (pad, _scalar(v)))
    return "\n".join(x for x in out if x != "")


def render(endpoints):
    head = ("# Generated by netdash (Dienste -> Monitoring). Do not edit by hand:\n"
            "# changes are overwritten. Source: %s\n\n" % STORE)
    return head + "endpoints:\n" + to_yaml(endpoints, 1) + "\n"


def _env():
    env = {"PATH": "/sbin:/bin:/usr/sbin:/usr/bin:/usr/local/sbin:/usr/local/bin", "GATUS_LOG_LEVEL": "WARN"}
    try:
        for line in open(ENV):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                env[k.strip()] = v.strip().strip('"').strip("'")
    except FileNotFoundError:
        pass
    return env


def clean(ep):
    """validate/normalise one endpoint coming from the UI"""
    if not isinstance(ep, dict):
        raise ValueError("Endpunkt muss ein Objekt sein")
    e = {k: v for k, v in ep.items() if v not in (None, "", [], {})}
    for f in ("name", "url"):
        if not str(e.get(f, "")).strip():
            raise ValueError("Feld '%s' fehlt" % f)
    e["name"] = str(e["name"]).strip()[:80]
    e["group"] = str(e.get("group", "")).strip()[:60] or "Allgemein"
    e["url"] = str(e["url"]).strip()[:500]
    if "conditions" in e:
        e["conditions"] = [str(c).strip() for c in e["conditions"] if str(c).strip()]
    if not e.get("conditions"):
        raise ValueError("Mindestens eine Bedingung ist nötig")
    if "interval" in e and not re.fullmatch(r"\d+(ms|s|m|h)", str(e["interval"])):
        raise ValueError("Intervall wie 30s, 1m oder 5m angeben")
    return e


class GatusConfig:
    def __init__(self):
        self.lock = threading.Lock()

    def available(self):
        return os.path.isdir(CONF_DIR) and os.path.exists(STORE)

    def load(self):
        with open(STORE, encoding="utf-8") as f:
            return json.load(f)

    def validate(self, endpoints):
        """Run Gatus with the candidate config on a scratch port for 6 s. Returns error text or None."""
        tmp = tempfile.mkdtemp(prefix="netdash-gatus-")
        try:
            base = open(os.path.join(sys.modules[__name__].CONF_DIR, "00-base.yaml"), encoding="utf-8").read()
            base = re.sub(r"(?m)^  address: .*$", "  address: 127.0.0.1", base, count=1)
            base = re.sub(r"(?m)^  port: \d+$", "  port: 18089", base, count=1)
            base = re.sub(r"(?m)^  path: .*gatus\.db.*$", "  path: %s/g.db" % tmp, base, count=1)
            base = base.replace("https://ntfy.sh", "http://127.0.0.1:9")
            os.makedirs(os.path.join(tmp, "config"))
            open(os.path.join(tmp, "config", "00-base.yaml"), "w", encoding="utf-8").write(base)
            open(os.path.join(tmp, "config", "50-netdash.yaml"), "w", encoding="utf-8").write(render(endpoints))
            env = _env()
            env["GATUS_CONFIG_PATH"] = os.path.join(tmp, "config")
            log = open(os.path.join(tmp, "log"), "w+")
            p = subprocess.Popen([BIN], env=env, stdout=log, stderr=subprocess.STDOUT, cwd=tmp,
                                 start_new_session=True)
            try:
                p.wait(timeout=6)
                log.seek(0)
                txt = log.read()
                m = re.search(r"panic: (.*)", txt)
                return (m.group(1) if m else txt.strip().splitlines()[-1] if txt.strip() else "Gatus beendet sich sofort")[:400]
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGTERM)
                try:
                    p.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(p.pid, signal.SIGKILL)
                return None
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def _write(self, endpoints):
        os.makedirs(BACKUPS, exist_ok=True)
        if os.path.exists(STORE):
            shutil.copy2(STORE, os.path.join(BACKUPS, time.strftime("endpoints-%Y%m%d-%H%M%S.json")))
            for old in sorted(os.listdir(BACKUPS))[:-30]:
                os.remove(os.path.join(BACKUPS, old))
        tmp = STORE + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(endpoints, f, indent=1, ensure_ascii=False)
        os.replace(tmp, STORE)
        tmp = OUT + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(render(endpoints))
        os.chmod(tmp, 0o644)
        os.replace(tmp, OUT)

    def apply(self, endpoints):
        err = self.validate(endpoints)
        if err:
            raise ValueError("Gatus lehnt die Konfiguration ab: " + err)
        self._write(endpoints)

    @staticmethod
    def _find(eps, group, name):
        for i, e in enumerate(eps):
            if e.get("name") == name and (e.get("group") or "") == (group or ""):
                return i
        return -1

    def upsert(self, ep, old=None):
        e = clean(ep)
        with self.lock:
            eps = self.load()
            idx = self._find(eps, (old or {}).get("group"), (old or {}).get("name")) if old else -1
            dup = self._find(eps, e["group"], e["name"])
            if dup >= 0 and dup != idx:
                raise ValueError("Es gibt schon einen Check '%s' in der Gruppe '%s'" % (e["name"], e["group"]))
            if idx >= 0:
                eps[idx] = e
            else:
                eps.append(e)
            self.apply(eps)
            return e

    def delete(self, group, name):
        with self.lock:
            eps = self.load()
            idx = self._find(eps, group, name)
            if idx < 0:
                raise ValueError("Check nicht gefunden")
            del eps[idx]
            self.apply(eps)


if __name__ == "__main__":
    # CLI: gatuscfg.py render | validate
    g = GatusConfig()
    if sys.argv[1:] == ["render"]:
        eps = g.load()
        err = g.validate(eps)
        if err:
            print("INVALID:", err)
            sys.exit(1)
        g._write(eps)
        print("written", OUT, len(eps), "endpoints")
    elif sys.argv[1:] == ["validate"]:
        print(g.validate(g.load()) or "ok")
    elif len(sys.argv) == 3 and sys.argv[1] == "validate-base":
        # check a new 00-base.yaml (from the monitoring project) together with the current endpoints
        global_conf = CONF_DIR
        tmpd = tempfile.mkdtemp(prefix="netdash-base-")
        shutil.copy(sys.argv[2], os.path.join(tmpd, "00-base.yaml"))
        CONF_DIR = tmpd
        err = g.validate(g.load())
        shutil.rmtree(tmpd, ignore_errors=True)
        print(err or "ok")
        sys.exit(1 if err else 0)
